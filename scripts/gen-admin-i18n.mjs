function deepTranslate(obj, mapFn) {
  if (typeof obj === "string") return mapFn(obj)
  if (Array.isArray(obj)) return obj.map((v) => deepTranslate(v, mapFn))
  if (obj && typeof obj === "object") {
    const out = {}
    for (const [k, v] of Object.entries(obj)) out[k] = deepTranslate(v, mapFn)
    return out
  }
  return obj
}

